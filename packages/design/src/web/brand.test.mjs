test('no file carries a favicon the generator does not write', () => {
  // The recipe's signature: a 32 unit tile with a radius of 7, in either quoting (the app inlines it as
  // a data: URI). A copy made by hand somewhere new would be stale the next time the mark or the accent moves.
  const signature = /width=['"]32['"] height=['"]32['"] rx=['"]7['"]/;
  const files = walkText(['apps', 'packages', 'tools', 'scripts', 'infra', 'tests', '.github']);
  assert.ok(files.length > 1500, `only ${files.length} files scanned; the walk has drifted`);
  const carriers = files.filter((f) => !f.rel.startsWith('packages/design/src/web/') && signature.test(readText(f))).map((f) => f.rel).sort();
  assert.deepEqual(carriers, [...FAVICON_COPIES, WEB_FAVICON_FILE].sort(), 'a favicon copy exists that scripts/make-brand-assets.mjs does not regenerate, or one it regenerates is gone');
});

test('every place that draws the mark draws the same path', () => {
  const sources = {
    'the site header and footer': ['apps/site/src/components/StudPilotMark.astro', (s) => pathOf(s)],
    'the app rail, sign-in and illustrations': ['apps/web/src/components/glyphs.tsx', (s) => /export const MARK_PATH = '([^']+)'/.exec(s)?.[1]],
    'the share card source': ['apps/site/brand/og.html', (s) => pathOf(s)],
    'the owner dashboard rail': ['scripts/owner-dashboard/control/index.html', (s) => /<svg class="brand-m"[^>]*><path d="([^"]+)"/.exec(s)?.[1]],
    'the owner dashboard registry': ['scripts/owner-dashboard/control/logos.js', (s) => /STUDPILOT_MARK = '<path d="([^"]+)"/.exec(s)?.[1]],
  };
  for (const [what, [rel, extract]] of Object.entries(sources)) {
    assert.equal(extract(read(rel)), MARK_PATH, `${what} (${rel}) does not draw the StudPilot mark`);
  }
  // The assistant's avatar spends the same constant rather than a path of its own.
  const model = read('apps/web/src/components/ws/model-mark.tsx');
  assert.match(model, /import \{ MARK_PATH \} from '\.\.\/glyphs'/, 'the assistant avatar does not import the mark');
  assert.doesNotMatch(model, /\sd="M/, 'the assistant avatar draws a path of its own');
});

