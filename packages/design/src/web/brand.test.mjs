/**
 * THE BRAND: one mark, drawn here, used everywhere, and the three old logos gone.
 *
 * packages/design/brand/studpilot-mark.svg is the only drawing of the StudPilot mark. Everything that
 * shows it (the site header and footer, the app's rail and sign-in screens, the assistant's avatar,
 * the favicons, the share card, the dashboards) carries that same path, and this file holds them
 * equal by READING each one, not by being told they are.
 *
 * The generated assets are held to their sources without a browser: a manifest records a hash of what
 * every PNG is made from and of every PNG as written (brand-recipe.mjs), and this file recomputes both
 * from the tree, so a changed mark, a changed token or a PNG that was swapped or left behind fails in
 * `pnpm -r test` on any machine. scripts/make-brand-assets.mjs --check adds a re-render and runs in CI.
 *
 * It also holds the retirement: the azure studded brick, the folded-sheet outline and the hexagon
 * holding a cube were three drawings in production at once (planning/sections/10-web-brand-design.md
 * 10.5.2). None of their files, none of their geometry and none of their palette may come back.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import {
  FAVICON_COPIES, MANIFEST_FILE, MARK_FILE, OG_SOURCE, PNGS, TOKENS_FILE, WEB_FAVICON_FILE,
  brandSources, cardLinks, cardProblems, iconSvg, manifestOf, manifestProblems, readManifest, withWebFavicon,
} from './brand-recipe.mjs';
import { ROOT, readText, walkText } from './tests/repo-walk.mjs';

const abs = (rel) => join(ROOT, rel);
const read = (rel) => readFileSync(abs(rel), 'utf8');
const BRAND = 'packages/design/brand';

const MARK = read(`${BRAND}/studpilot-mark.svg`);
/** The number of drawing commands in an SVG path `d`: every command letter, either case, and not an exponent's e. */
const pathCommands = (d) => [...d.replace(/\d[eE][+-]?\d/g, '0').matchAll(/[MLHVCSQTAZmlhvcsqtaz]/g)].length;
const pathOf = (src) => /\sd="([^"]+)"/.exec(src)?.[1] ?? null;
const MARK_PATH = pathOf(MARK);

/** Width and height of a PNG, read from its IHDR chunk. Throws on anything that is not a PNG. */
function pngSize(rel) {
  const b = readFileSync(abs(rel));
  assert.equal(b.subarray(1, 4).toString('latin1'), 'PNG', `${rel} is not a PNG`);
  return [b.readUInt32BE(16), b.readUInt32BE(20)];
}

/* ------------------------------------------------------------------ the mark */

test('the mark is one filled path in currentColor, simple enough for 16 px', () => {
  assert.ok(MARK_PATH, 'no path in studpilot-mark.svg');
  assert.match(MARK, /<svg[^>]*viewBox="0 0 32 32"/, 'the mark is drawn on a 32 unit canvas');
  assert.match(MARK, /<svg[^>]*fill="currentColor"/, 'the mark must take its colour from the page (currentColor)');
  assert.equal([...MARK.matchAll(/<path\b/g)].length, 1, 'the mark is one path');
  assert.doesNotMatch(MARK, /#[0-9a-f]{3,8}\b|rgba?\(|<image|<text|<linearGradient|<radialGradient|filter=/i, 'the mark carries a hard-coded colour, a gradient, an image or text');
  assert.match(MARK, /fill-rule="evenodd"/, 'the stud must be a real hole (even-odd), not a painted circle');
  assert.equal([...MARK_PATH.matchAll(/Z/gi)].length, 2, 'expected exactly two closed shapes: the tile and the stud');
  // Few segments: a mark that survives 16 px has little in it. Counting path commands is the proxy.
  assert.ok(pathCommands(MARK_PATH) <= 24, `the mark has ${pathCommands(MARK_PATH)} path commands; that is too intricate to read at 16 px`);
  assert.ok(pathCommands(MARK_PATH) >= 8, 'the command count is implausibly low; the proxy is not reading the path');
});

test('the guard has teeth: the intricacy proxy counts every path command, cubic and smooth curves included', () => {
  // The first version counted M L H V Q A Z and every LOWERCASE letter, so an absolute C, S or T
  // (a cubic, a smooth cubic, a smooth quadratic) was not counted: a mark drawn in cubics read as simple.
  assert.equal(pathCommands('M0 0C1 1 2 2 3 3C4 4 5 5 6 6S7 7 8 8T9 9Z'), 6, 'an absolute C, S or T was not counted');
  assert.equal(pathCommands('m0 0c1 1 2 2 3 3s4 4 5 5t6 6z'), 5, 'a relative c, s or t was not counted');
  assert.equal(pathCommands('M12 3H27.8Q29 3 29 4.2V20A9 9 0 0 1 20 29Z'), 6, 'the drawing\'s own commands miscounted');
  assert.equal(pathCommands('M1e-3 2E+2L3 4'), 2, 'an exponent in a number was counted as a command');
  const flower = 'M0 0' + 'C1 1 2 2 3 3'.repeat(30) + 'Z';
  assert.ok(pathCommands(flower) > 24, 'a path of thirty cubics passed the intricacy bar');
});

