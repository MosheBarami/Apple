#!/usr/bin/env node
// Regenerates docs/evals/RESULTS.md (repo-level) from every results/*.json.
// One table row per (run, model); one column per category plus overall.
//   node src/report.mjs
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS_DIR = join(HERE, '..', 'results');
const REPO_ROOT = join(HERE, '..', '..', '..');
const OUT_FILE = join(REPO_ROOT, 'docs', 'evals', 'RESULTS.md');

function loadAll() {
  let files = [];
  try {
    files = readdirSync(RESULTS_DIR)
      .filter((f) => f.endsWith('.json'))
      .sort();
  } catch {
    return [];
  }
  const runs = [];
  for (const f of files) {
    try {
      const data = JSON.parse(readFileSync(join(RESULTS_DIR, f), 'utf8'));
      if (data.runMeta && data.perCategory && data.overall) runs.push({ file: f, ...data });
    } catch {
      console.error(`skipping unreadable results file: ${f}`);
    }
  }
  return runs;
}

function pct(n) {
  return (n * 100).toFixed(1);
}

function main() {
  const runs = loadAll();
  const categories = [...new Set(runs.flatMap((r) => r.perCategory.map((c) => c.category)))].sort();

  const lines = [];
  lines.push('# Golem eval results');
  lines.push('');
  lines.push('Auto-generated by `packages/evals/src/report.mjs` from `packages/evals/results/*.json` — do not edit by hand.');
  lines.push(`Regenerated: ${new Date().toISOString()}. Scores are 0–100 (weighted % of checks passed).`);
  lines.push('');
  if (runs.length === 0) {
    lines.push('_No eval runs recorded yet. Run `node src/run.mjs --tag <name>` in packages/evals to produce one._');
  } else {
    lines.push(`| run | model | ${categories.join(' | ')} | overall |`);
    lines.push(`|---|---|${categories.map(() => '---:').join('|')}|---:|`);
    for (const run of runs) {
      for (const model of run.runMeta.models ?? [...new Set(run.overall.map((o) => o.model))]) {
        const cells = categories.map((cat) => {
          const hit = run.perCategory.find((c) => c.model === model && c.category === cat);
          return hit ? pct(hit.score) : '—';
        });
        const overall = run.overall.find((o) => o.model === model);
        lines.push(`| ${run.runMeta.tag} | ${model} | ${cells.join(' | ')} | ${overall ? pct(overall.score) : '—'} |`);
      }
    }
    lines.push('');
    lines.push('## Runs');
    lines.push('');
    for (const run of runs) {
      const errs = (run.perTask ?? []).filter((t) => !t.ok).length;
      lines.push(
        `- **${run.runMeta.tag}** — \`${run.file}\` · ${run.runMeta.startedAt ?? '?'} · ${run.runMeta.jobCount ?? '?'} jobs · ` +
          `checker: ${run.runMeta.luauChecker ?? 'none'}${errs ? ` · ${errs} transport error(s)` : ''}`,
      );
    }
  }
  lines.push('');
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, lines.join('\n'));
  console.log(`wrote ${OUT_FILE} (${runs.length} run(s), ${categories.length} categories)`);
}

main();
