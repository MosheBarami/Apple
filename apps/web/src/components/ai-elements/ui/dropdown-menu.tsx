// Adapted from AI Elements `packages/shadcn-ui/components/ui/dropdown-menu.tsx` at the pinned commit
// (see ../NOTICE). The fifteen shadcn wrappers below — names, props, `data-slot`s and inert Tailwind
// strings — are upstream's, and they still read `DropdownMenuPrimitive.<Part>`, so the file diffs
// against its copy wrapper for wrapper. What changed is what `DropdownMenuPrimitive` is: not Radix,
// which this app does not install, but the local implementation in ./dropdown-menu-primitive.tsx.
//
// What it keeps from Radix's DropdownMenu, because the AI Elements wrappers rely on it:
//   * the trigger is a button with `aria-haspopup="menu"`, `aria-expanded`, and — while the menu is
//     open — `aria-controls`; a left-button pointer-down toggles it (and does not steal focus), and
//     Enter, Space or ArrowDown open it from the keyboard;
//   * the content is `role="menu"`, labelled by its trigger unless it is given its own
//     `aria-label`, portalled to <body> and placed with position:fixed (../lib/floating) on the
//     requested side — flipping when that side has no room — so no `overflow:hidden` ancestor can
//     clip it;
//   * items are `menuitem`, `menuitemcheckbox` or `menuitemradio`, reached with ArrowUp/ArrowDown/
//     Home/End (no wrap, Radix's default), highlighted by the pointer as it moves, chosen with a
//     click, Enter or Space; `onSelect(event)` runs first and `event.preventDefault()` keeps the
//     menu open, exactly as Radix documents it;
//   * a `disabled` item is skipped and cannot be chosen; Escape closes and hands focus back to the
//     trigger, and so does choosing an item; a pointer-down outside closes;
//   * checkbox and radio items carry `aria-checked`, and ItemIndicator renders only while checked;
//   * sub-menus open to the side with ArrowRight, a click or a hover, and close with ArrowLeft.
// What it does not do: typeahead, `modal` pointer blocking and the `loop` option (accepted, not
// implemented). Tab closes the menu and returns focus to the trigger rather than being swallowed.
